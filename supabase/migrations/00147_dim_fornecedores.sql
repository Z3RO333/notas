-- 00147_dim_fornecedores.sql
--
-- Tabela dimensão de fornecedores SAP.
-- Permite join com ordens_financeiro_importado.fornecedor_codigo para
-- exibir nome padronizado e evitar divergências de grafia.

CREATE TABLE IF NOT EXISTS public.dim_fornecedores (
  codigo TEXT PRIMARY KEY,
  nome   TEXT NOT NULL
);

COMMENT ON TABLE public.dim_fornecedores IS
  'Dimensão de fornecedores SAP: código → nome canônico.';

ALTER TABLE public.dim_fornecedores ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Autenticado lê fornecedores" ON public.dim_fornecedores;
CREATE POLICY "Autenticado lê fornecedores"
  ON public.dim_fornecedores FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "Gestor escreve fornecedores" ON public.dim_fornecedores;
CREATE POLICY "Gestor escreve fornecedores"
  ON public.dim_fornecedores FOR ALL TO authenticated
  USING (get_my_role() = 'gestor'::user_role)
  WITH CHECK (get_my_role() = 'gestor'::user_role);

